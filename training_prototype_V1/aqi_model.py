class AIQTrainingPipeline:
    """Prepare aiq_training_cam using the notebook's feature/scaling logic."""

    def __init__(self, cfg: Config):
        self.cfg = cfg
        self.feature_cols: List[str] = []
        self.ae_scaler = MinMaxScaler() # Use MinMaxScaler for autoencoder, StandardScaler for LSTM sequences (after AE transformation)
        self.lstm_scaler = StandardScaler()


        self.train_df = None
        self.test_df = None

        self.X_train = self.X_val = self.X_test = None
        self.y_train = self.y_val = self.y_test = None

        self.X_train_seq = self.X_val_seq = self.X_test_seq = None
        self.y_train_seq = self.y_val_seq = self.y_test_seq = None


    def prepare(self) -> "AIQTrainingPipeline":
        air_weather_df = self._load_and_engineer()
        self.train_df, self.val_df, self.test_df = self._split_scale(air_weather_df)

        # row-level arrays for AE
        self.X_train = self.train_df[self.feature_cols].values.astype(np.float32)
        self.X_val = self.val_df[self.feature_cols].values.astype(np.float32)
        self.X_test = self.test_df[self.feature_cols].values.astype(np.float32)
        
        self.y_train = self.train_df[self.cfg.target_col].values.reshape(-1, 1).astype(np.float32)
        self.y_val = self.val_df[self.cfg.target_col].values.reshape(-1, 1).astype(np.float32)
        self.y_test = self.test_df[self.cfg.target_col].values.reshape(-1, 1).astype(np.float32)

        # grouped sequences for LSTM
        self.X_train_seq, self.y_train_seq = self.make_sequences(self.train_df)
        self.X_val_seq, self.y_val_seq = self.make_sequences(self.val_df)
        self.X_test_seq, self.y_test_seq = self.make_sequences(self.test_df)

        print(f"Train rows: {self.train_df.shape}, Test rows: {self.test_df.shape}")
        print(f"Train seq: {self.X_train_seq.shape}, Test seq: {self.X_test_seq.shape}")
        return self

    def _load_and_engineer(self) -> pd.DataFrame:
        air_df = pd.read_csv(self.cfg.air_data_path)
        weather_df = pd.read_csv(self.cfg.weather_data_path)
        air_weather_df = pd.merge(
            air_df, weather_df, on=["time", "zip", "city", "state"], how="inner"
        )

        coords = air_weather_df["zip"].map(zip_code_to_lat_long_map)
        air_weather_df["latitude"] = coords.str[0]
        air_weather_df["longitude"] = coords.str[1]

        air_weather_df["time"] = pd.to_datetime(air_weather_df["time"], utc=True)
        air_weather_df = air_weather_df.sort_values(["zip", "time"]).reset_index(drop=True)

        air_weather_df["hour_sin"] = np.sin(2 * np.pi * air_weather_df["time"].dt.hour / 24)
        air_weather_df["hour_cos"] = np.cos(2 * np.pi * air_weather_df["time"].dt.hour / 24)
        air_weather_df["day_of_week_sin"] = np.sin(2 * np.pi * air_weather_df["time"].dt.dayofweek / 7)
        air_weather_df["day_of_week_cos"] = np.cos(2 * np.pi * air_weather_df["time"].dt.dayofweek / 7)
        air_weather_df["month_sin"] = np.sin(2 * np.pi * air_weather_df["time"].dt.month / 12)
        air_weather_df["month_cos"] = np.cos(2 * np.pi * air_weather_df["time"].dt.month / 12)

        air_weather_df["hour"] = air_weather_df["time"].dt.hour
        air_weather_df["day_of_week"] = air_weather_df["time"].dt.dayofweek
        air_weather_df["is_weekend"] = air_weather_df["day_of_week"].isin([5, 6]).astype(int)
        air_weather_df["month"] = air_weather_df["time"].dt.month
        air_weather_df["day"] = air_weather_df["time"].dt.day

        # IMPORTANT: do NOT drop zip yet
        x = air_weather_df.drop(columns=self.cfg.cols_to_drop)

        # zip stays only for grouping, not as a model feature
        self.feature_cols = [c for c in x.columns if c != "zip"]
        self._df = air_weather_df

        print(f"Loaded: {air_weather_df.shape}")
        print(f"Target: {self.cfg.target_col}")
        print(f"Features ({len(self.feature_cols)}): {self.feature_cols}")
        return air_weather_df

    def _split_scale(self, air_weather_df: pd.DataFrame):
        train_parts = []
        test_parts = []
        val_parts = []

        for zip_code, group in air_weather_df.groupby("zip"):
            group = group.sort_values("time").reset_index(drop=True)
            split_idx_train = int(len(group) * self.cfg.train_size)
            split_idx_val = int(len(group) * (1 - self.cfg.val_size))
            split_idx_test = int(len(group) * (1 - self.cfg.test_size))

            train_parts.append(group.iloc[:split_idx_train].copy())
            val_parts.append(group.iloc[split_idx_train:split_idx_val].copy())
            test_parts.append(group.iloc[split_idx_val:split_idx_test].copy())

        train_df = pd.concat(train_parts, axis=0).reset_index(drop=True)
        val_df = pd.concat(val_parts, axis=0).reset_index(drop=True)
        test_df = pd.concat(test_parts, axis=0).reset_index(drop=True)

        train_df[self.feature_cols] = self.ae_scaler.fit_transform(
            train_df[self.feature_cols].astype(np.float32)
        )
        val_df[self.feature_cols] = self.ae_scaler.transform(
            val_df[self.feature_cols].astype(np.float32)
        )
        test_df[self.feature_cols] = self.ae_scaler.transform(
            test_df[self.feature_cols].astype(np.float32)
        )

        train_df[self.feature_cols] = np.nan_to_num(
            train_df[self.feature_cols], nan=0.0, posinf=0.0, neginf=0.0
        )
        val_df[self.feature_cols] = np.nan_to_num(
            val_df[self.feature_cols], nan=0.0, posinf=0.0, neginf=0.0
        )
        test_df[self.feature_cols] = np.nan_to_num(
            test_df[self.feature_cols], nan=0.0, posinf=0.0, neginf=0.0
        )

        return train_df, val_df, test_df

    @property
    def input_dim(self) -> int:
        return len(self.feature_cols) + 1

    def make_sequences(self, df: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray]:
        lookback, horizon = self.cfg.lookback, self.cfg.horizon
        Xs, ys = [], []

        for zip_code, group in df.groupby("zip"):
            group = group.sort_values("time").reset_index(drop=True)

            X = group[self.feature_cols].values.astype(np.float32)
            y = group[self.cfg.target_col].values.astype(np.float32)

            if len(group) < lookback + horizon:
                continue

            for i in range(lookback, len(group) - horizon + 1):
              past_features = X[i-lookback:i]
              past_aqi = y[i-lookback:i].reshape(lookback, 1)

              seq = np.concatenate([past_features, past_aqi], axis=1)

              Xs.append(seq)
              ys.append(y[i + horizon - 1])

        return np.array(Xs, dtype=np.float32), np.array(ys, dtype=np.float32)

